"""Validation utilities for the project dataset."""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd


REQUIRED_COLUMNS = {"text", "sentiment"}
ALLOWED_SENTIMENTS = {"negative", "neutral", "positive"}


@dataclass
class ValidationReport:
    """Results produced while checking a dataset."""

    total_rows: int
    empty_text_rows: int
    empty_sentiment_rows: int
    invalid_sentiments: dict[str, int]
    exact_duplicate_rows: int
    conflicting_duplicate_texts: int
    class_distribution: dict[str, int]
    errors: list[str] = field(default_factory=list)

    @property
    def is_valid(self) -> bool:
        return not self.errors


def _normalized_series(series: pd.Series) -> pd.Series:
    return series.fillna("").astype(str).str.strip().str.casefold()


def validate_dataset(path: str | Path) -> ValidationReport:
    """Validate a CSV dataset against the project's data contract.

    The function does not modify the source file. Sentiment comparisons ignore
    leading/trailing whitespace and letter case, but the CSV should still use
    canonical lowercase labels when it is generated by this project.
    """

    dataset_path = Path(path)
    if not dataset_path.is_file():
        raise FileNotFoundError(f"Dataset file was not found: {dataset_path}")

    try:
        frame = pd.read_csv(dataset_path, dtype="string", encoding="utf-8")
    except UnicodeDecodeError as error:
        raise ValueError("Dataset must be encoded as UTF-8.") from error
    except pd.errors.ParserError as error:
        raise ValueError("Dataset could not be parsed as a CSV file.") from error

    missing_columns = REQUIRED_COLUMNS.difference(frame.columns)
    if missing_columns:
        names = ", ".join(sorted(missing_columns))
        raise ValueError(f"Dataset is missing required column(s): {names}")

    normalized_text = _normalized_series(frame["text"])
    normalized_sentiment = _normalized_series(frame["sentiment"])

    empty_text_rows = int(normalized_text.eq("").sum())
    empty_sentiment_rows = int(normalized_sentiment.eq("").sum())
    invalid_mask = (~normalized_sentiment.isin(ALLOWED_SENTIMENTS)) & normalized_sentiment.ne("")
    invalid_sentiments = (
        normalized_sentiment[invalid_mask].value_counts().sort_index().astype(int).to_dict()
    )

    normalized_frame = pd.DataFrame(
        {"text": normalized_text, "sentiment": normalized_sentiment}
    )
    exact_duplicate_rows = int(normalized_frame.duplicated().sum())

    valid_texts = normalized_frame[normalized_frame["text"].ne("")]
    labels_per_text = valid_texts.groupby("text")["sentiment"].nunique()
    conflicting_duplicate_texts = int(labels_per_text.gt(1).sum())

    class_distribution = (
        normalized_sentiment[normalized_sentiment.isin(ALLOWED_SENTIMENTS)]
        .value_counts()
        .reindex(sorted(ALLOWED_SENTIMENTS), fill_value=0)
        .astype(int)
        .to_dict()
    )

    errors: list[str] = []
    if frame.empty:
        errors.append("Dataset has no rows.")
    if empty_text_rows:
        errors.append(f"{empty_text_rows} row(s) have empty text values.")
    if empty_sentiment_rows:
        errors.append(f"{empty_sentiment_rows} row(s) have empty sentiment values.")
    if invalid_sentiments:
        labels = ", ".join(sorted(invalid_sentiments))
        errors.append(f"Invalid sentiment label(s) found: {labels}.")
    if exact_duplicate_rows:
        errors.append(f"{exact_duplicate_rows} exact duplicate row(s) found.")
    if conflicting_duplicate_texts:
        errors.append(
            f"{conflicting_duplicate_texts} text value(s) have conflicting sentiment labels."
        )

    return ValidationReport(
        total_rows=len(frame),
        empty_text_rows=empty_text_rows,
        empty_sentiment_rows=empty_sentiment_rows,
        invalid_sentiments=invalid_sentiments,
        exact_duplicate_rows=exact_duplicate_rows,
        conflicting_duplicate_texts=conflicting_duplicate_texts,
        class_distribution=class_distribution,
        errors=errors,
    )


def format_report(report: ValidationReport) -> str:
    """Format a validation report for command-line output."""

    lines = [
        "Dataset validation report",
        "=" * 25,
        f"Rows found: {report.total_rows}",
        f"Empty text rows: {report.empty_text_rows}",
        f"Empty sentiment rows: {report.empty_sentiment_rows}",
        f"Exact duplicate rows: {report.exact_duplicate_rows}",
        f"Conflicting duplicate texts: {report.conflicting_duplicate_texts}",
        "Class distribution:",
    ]
    lines.extend(f"- {label}: {count}" for label, count in report.class_distribution.items())

    if report.invalid_sentiments:
        lines.append("Invalid sentiments:")
        lines.extend(
            f"- {label}: {count}" for label, count in report.invalid_sentiments.items()
        )

    if report.is_valid:
        lines.append("Validation passed.")
    else:
        lines.append("Validation failed:")
        lines.extend(f"- {error}" for error in report.errors)

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate a sentiment CSV dataset.")
    parser.add_argument("--input", type=Path, required=True, help="Path to the input CSV file.")
    args = parser.parse_args()

    try:
        report = validate_dataset(args.input)
    except (FileNotFoundError, ValueError) as error:
        print(f"Validation failed: {error}")
        return 1

    print(format_report(report))
    return 0 if report.is_valid else 1


if __name__ == "__main__":
    raise SystemExit(main())
